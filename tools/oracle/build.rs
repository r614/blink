//! The headless presentation shim (`src/present.rs`) runs the runtime's own event-to-effect
//! and event-to-sound code, not a copy: this script cuts those items out of
//! `crates/dishonored_runtime/src/{effects,audio,characters,npc_anim}.rs` (which link Bevy)
//! and writes them to `$OUT_DIR/present_extract.rs`, where `present.rs` compiles them against
//! small stand-ins for the Bevy resources. A change of those items in the runtime is picked up
//! by the next build; a change the stand-ins do not cover fails this build with the generated
//! file's path in the error, so the shim can never silently drift from the game.

use std::path::{Path, PathBuf};

/// End of the item starting at `start`: the matching `}` of its first top-level `{`, or the
/// first top-level `;` before any `{`. Skips strings, chars and comments.
fn item_end(s: &[u8], start: usize) -> Option<usize> {
    let mut depth = 0i32;
    let mut i = start;
    let mut opened = false;
    while i < s.len() {
        let c = s[i];
        match c {
            b'/' if s.get(i + 1) == Some(&b'/') => {
                while i < s.len() && s[i] != b'\n' {
                    i += 1;
                }
                continue;
            }
            b'"' => {
                i += 1;
                while i < s.len() && s[i] != b'"' {
                    if s[i] == b'\\' {
                        i += 1;
                    }
                    i += 1;
                }
            }
            // Char literals ('x', '\n'); lifetimes ('a) have no closing quote right after.
            b'\'' if s.get(i + 2) == Some(&b'\'') => i += 2,
            b'\'' if s.get(i + 1) == Some(&b'\\') && s.get(i + 3) == Some(&b'\'') => i += 3,
            b'{' | b'(' | b'[' => {
                if c == b'{' && depth == 0 {
                    opened = true;
                }
                depth += 1;
            }
            b'}' | b')' | b']' => {
                depth -= 1;
                if depth == 0 && c == b'}' && opened {
                    return Some(i + 1);
                }
            }
            b';' if depth == 0 && !opened => return Some(i + 1),
            _ => {}
        }
        i += 1;
    }
    None
}

fn item(src: &str, file: &Path, head: &str) -> String {
    let start = src.find(head).unwrap_or_else(|| panic!("present shim: `{head}` not found in {} (the runtime changed: update tools/oracle/build.rs and src/present.rs)", file.display()));
    let end = item_end(src.as_bytes(), start).unwrap_or_else(|| panic!("present shim: unterminated `{head}` in {}", file.display()));
    src[start..end].to_string()
}

/// The statements of a function body from the first line starting with `from` to the body's end.
fn body_from(src: &str, file: &Path, func: &str, from: &str) -> String {
    let f = item(src, file, func);
    let open = f.find('{').unwrap();
    let body = &f[open + 1..f.len() - 1];
    let k = body.find(from).unwrap_or_else(|| panic!("present shim: `{from}` not found in `{func}` of {}", file.display()));
    body[k..].to_string()
}

/// One statement / block of a function body starting with `head`.
fn block_in(src: &str, file: &Path, func: &str, head: &str) -> String {
    let f = item(src, file, func);
    let k = f.find(head).unwrap_or_else(|| panic!("present shim: `{head}` not found in `{func}` of {}", file.display()));
    let end = item_end(f.as_bytes(), k).unwrap();
    f[k..end].to_string()
}

fn main() {
    let dst = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("present_extract.rs");
    if std::env::var_os("CARGO_FEATURE_SCENARIOS").is_none() {
        // The collision-only build has no presentation shim.
        std::fs::write(&dst, "").unwrap();
        return;
    }
    let rt =PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../crates/dishonored_runtime/src");
    let read = |f: &str| {
        let p = rt.join(f);
        println!("cargo:rerun-if-changed={}", p.display());
        (std::fs::read_to_string(&p).unwrap_or_else(|e| panic!("present shim: {}: {e}", p.display())), p)
    };
    let (fx, fxp) = read("effects.rs");
    let (au, aup) = read("audio.rs");
    let (ch, chp) = read("characters.rs");
    let (na, nap) = read("npc_anim.rs");
    let mut out = String::from("// @generated by tools/oracle/build.rs from crates/dishonored_runtime/src: do not edit.\n");
    let mut push = |label: &str, text: String| {
        out.push_str(&format!("\n// ---- {label} ----\n{text}\n"));
    };
    for c in ["pub const PLAYER_MUZZLE", "pub const PAWN_MUZZLE", "pub const SHADOW_KILL_PS", "pub const SHADOW_KILL_DELAY", "pub const GAMEPLAY_PARTICLES", "const MAX_PARTICLES"] {
        push("effects.rs", item(&fx, &fxp, c));
    }
    push("effects.rs", format!("#[derive(Default)]\n{}", item(&fx, &fxp, "pub struct EffectSockets")));
    push("effects.rs", format!("#[derive(Clone, Copy, Default)]\n{}", item(&fx, &fxp, "pub struct Particle ")));
    push("effects.rs", item(&fx, &fxp, "pub struct EmitterSim"));
    push("effects.rs", item(&fx, &fxp, "impl Default for EmitterSim"));
    push("effects.rs", item(&fx, &fxp, "type RayFn"));
    push("effects.rs", item(&fx, &fxp, "fn d3("));
    push("effects.rs", item(&fx, &fxp, "fn spawn_particle("));
    push("effects.rs", item(&fx, &fxp, "pub fn step("));
    // `spawn_effect`'s emitter frame (X along the direction).
    let frame = body_from(&fx, &fxp, "pub fn spawn_effect(", "let x = if dir");
    let frame = frame.split("let level").next().unwrap().to_string();
    push("effects.rs (spawn_effect: emitter frame)", format!("fn effect_transform(at: Vec3, dir: Vec3) -> Mat4 {{\n{frame}\nm\n}}"));
    push("effects.rs (Effects::rand)", format!("impl FxShim {{\n{}\n}}", item(&fx, &fxp, "fn rand(&mut self)")));
    // `simulate`'s one-shot despawn rule, as an expression over `inst`.
    let rule = block_in(&fx, &fxp, "fn simulate(", "if inst.one_shot && inst.sims");
    let cond = rule.trim_start_matches("if ").split(" {").next().unwrap().to_string();
    push("effects.rs (simulate: one-shot despawn)", format!("fn despawned(inst: &FxInstanceShim) -> bool {{\n    {cond}\n}}"));
    push(
        "effects.rs (gameplay_effects)",
        format!(
            "#[allow(unused_variables, unused_mut, clippy::all)]\nfn gameplay_effects_body(mut commands: (), mut meshes: (), mut fx: &mut FxShim, view: &SessionView, audio: Option<&AudioShim>, sockets: &EffectSockets, session: Option<&Session>, now: f32, events: Vec<SimEvent>) {{\n{}\n}}",
            body_from(&fx, &fxp, "fn gameplay_effects(", "let due:")
        ),
    );
    for c in ["const PLAYER_OBJ", "const TEMP_OBJ"] {
        push("audio.rs", item(&au, &aup, c));
    }
    push("audio.rs", item(&au, &aup, "fn player<'a>("));
    push("audio.rs", item(&au, &aup, "fn surface_below("));
    push("audio.rs", item(&au, &aup, "fn surface_near("));
    push(
        "audio.rs (drive: simulation events)",
        format!(
            "#[allow(unused_variables, unused_mut, clippy::all)]\nfn audio_events_body(audio: &mut AudioShim, mut e: EngineShim, view: &SessionView, session: &Session, me: Option<PlayerId>, now: f32, events: Vec<SimEvent>) -> EngineShim {{\n{}\ne\n}}",
            block_in(&au, &aup, "pub fn drive(", "for ev in events {")
        ),
    );
    push("npc_anim.rs", format!("#[derive(Debug, Clone, Copy, PartialEq)]\n{}", item(&na, &nap, "pub enum HitKind")));
    push("characters.rs", item(&ch, &chp, "fn collect_hits(").replace("crate::npc_anim::", ""));
    std::fs::write(&dst, out).unwrap();
}
